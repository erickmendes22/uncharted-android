size_t runtime_find_guest_fix(const unsigned char *code, size_t size, const char *pattern,
                             size_t *found, size_t *length) {
    unsigned char bytes[256], mask[256]; size_t n=0, matches=0, first=0;
    *length=0;
    for (const char *p=pattern; *p;) {
        if (*p==' ') { ++p; continue; }
        if (n==sizeof(bytes) || !p[1]) return 0;
        if (p[0]=='?' && p[1]=='?') { bytes[n]=0; mask[n++]=0; p+=2; continue; }
        char pair[3]={p[0],p[1],0}, *end;
        long value=strtol(pair,&end,16);
        if (*end || value<0 || value>255) return 0;
        bytes[n]=(unsigned char)value; mask[n++]=1; p+=2;
    }
    *length=n;
    while (first<n && !mask[first]) ++first;
    if (first==n || size<n) return 0;
    for (size_t i=0; i<=size-n; ++i) {
        if (code[i+first]!=bytes[first]) continue;
        size_t k=0; while (k<n && (!mask[k] || code[i+k]==bytes[k])) ++k;
        if (k==n) { if (!matches) *found=i; if (++matches>1) return matches; }
    }
    return matches;
}
