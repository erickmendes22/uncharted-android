#!/usr/bin/env python3
"""Generates tests/PS4.S: Remill tests (lifted vs native) for the semantics of PS4_AVX.cpp.
Run: python3 gen_tests.py > tests/PS4.S
Every test: xmm1..3 from three 64-bit arguments through the stack, garbage in the high bits of ymm4
(checking VEX.128 zeroing), then the instruction with the destination xmm4/ymm4/eax/[rsp]."""

INT = """0x0123456789abcdef, 0xfedcba9876543210, 0x8000000080000000,
    0x7fffffff7fffffff, 0x0000ffff0000ffff, 0x00ff00ff80018001,
    0xffffffffffffffff, 0x0000000000000000, 0x1111222233334444,
    0x8080808080808080, 0x0f0e0d0c0b0a0908, 0x0706050403020100,
    0x8000800080007fff, 0x7fff7fff00010002, 0xfffe0003c0004000"""
FP32 = """0x3f80000040000000, 0xbf800000c0490fdb, 0x7fc0000000000000,
    0x800000007f800000, 0x0000000100800000, 0x412000003e800000,
    0x3fc00000bfc00000, 0x40200000c0600000, 0x4b7fffffcb000001,
    0xff800000ffc00001, 0x3eaaaaab42f6e979, 0x7f7fffff00000000,
    0x3f000000bf000000, 0x40400000c0400000, 0x00000000000003e8"""
FP64 = """0x4004000000000000, 0xc00c000000000000, 0x3ff8000000000000,
    0x7ff8000000000001, 0x8000000000000000, 0x4330000000000001,
    0xbfe0000000000000, 0x7ff0000000000000, 0x3fe0000000000001,
    0xc004000000000000, 0x0000000000000001, 0x4012000000000000"""
HALF = """0x3c00bc007c00fc00, 0x7c017e0000018000, 0x03ff04003555c000,
    0x7bff0001fbff3800, 0x0000000000000000, 0xfe01fc018400c400"""
GPR = """0x0000000000000000, 0x0000000000000001, 0x8000000000000000,
    0x00000000fffffff0, 0x0123456789abcdef, 0xffffffffffffffff,
    0x0000000080000000, 0x0000001000000000, 0x7ffffffffffffffe"""

LOAD = """    push ARG2_64
    push ARG1_64
    vmovdqu xmm1, xmmword ptr [rsp]
    push ARG1_64
    push ARG3_64
    vmovdqu xmm2, xmmword ptr [rsp]
    push ARG3_64
    push ARG2_64
    vmovdqu xmm3, xmmword ptr [rsp]
    vinsertf128 ymm4, ymm4, xmm2, 1"""
YMM = """    vinsertf128 ymm1, ymm1, xmm2, 1
    vinsertf128 ymm2, ymm2, xmm3, 1
    vinsertf128 ymm3, ymm3, xmm1, 1"""

out = ['/* Generated by uncharted-g2 scripts/remill/gen_tests.py — do not edit. */', '',
       '#if HAS_FEATURE_AVX', '']
n = 0


def test(name, inputs, body, ymm=False):
    global n
    n += 1
    out.append(f'TEST_BEGIN_64(PS4_{name}, 3)')
    out.append(f'TEST_INPUTS(\n    {inputs})')
    out.append(LOAD)
    if ymm:
        out.append(YMM)
    out.extend('    ' + line for line in body.split(';'))
    out.append('TEST_END_64')
    out.append('')


def ident(s):
    return s.replace(' ', '_').replace(',', '').replace('[', '').replace(']', '')


# --- new semantics: register forms with immediates ---
for imm in ('0x1b', '0xe4', '0x00', '0x93'):
    test(f'VPERMILPSxmm_{imm}', FP32, f'vpermilps xmm4, xmm1, {imm}')
    test(f'VPERMILPSmem_{imm}', FP32, f'vpermilps xmm4, xmmword ptr [rsp], {imm}')
    test(f'VPERMILPSymm_{imm}', FP32, f'vpermilps ymm4, ymm1, {imm}', ymm=True)
for imm in ('0', '1', '2', '3'):
    test(f'VPERMILPDxmm_{imm}', FP64, f'vpermilpd xmm4, xmm1, {imm}')
    test(f'VPERMILPDymm_{imm}', FP64, f'vpermilpd ymm4, ymm1, {int(imm) * 5}', ymm=True)
for imm in ('0x1b', '0x6d', '0xb1', '0x4e'):
    test(f'VSHUFPSxmm_{imm}', FP32, f'vshufps xmm4, xmm1, xmm2, {imm}')
    test(f'VSHUFPSmem_{imm}', FP32, f'vshufps xmm4, xmm1, xmmword ptr [rsp], {imm}')
    test(f'VSHUFPSymm_{imm}', FP32, f'vshufps ymm4, ymm1, ymm2, {imm}', ymm=True)
for imm in ('0x5', '0xa', '0xf', '0x0'):
    test(f'VBLENDPSxmm_{imm}', FP32, f'vblendps xmm4, xmm1, xmm2, {imm}')
    test(f'VBLENDPSmem_{imm}', FP32, f'vblendps xmm4, xmm1, xmmword ptr [rsp], {imm}')
test('VBLENDPSymm_96', FP32, 'vblendps ymm4, ymm1, ymm2, 0x96', ymm=True)
test('VBLENDVPSxmm', INT, 'vblendvps xmm4, xmm1, xmm2, xmm3')
test('VBLENDVPSmem', INT, 'vblendvps xmm4, xmm1, xmmword ptr [rsp], xmm2')
test('VBLENDVPSymm', INT, 'vblendvps ymm4, ymm1, ymm2, ymm3', ymm=True)
test('VBLENDVPDxmm', INT, 'vblendvpd xmm4, xmm1, xmm2, xmm3')
test('VPBLENDVBxmm', INT, 'vpblendvb xmm4, xmm1, xmm2, xmm3')
test('VPBLENDVBmem', INT, 'vpblendvb xmm4, xmm1, xmmword ptr [rsp], xmm3')
for imm in ('0x00', '0x5c', '0xd3', '0x3f', '0x90'):
    test(f'VINSERTPSreg_{imm}', FP32, f'vinsertps xmm4, xmm1, xmm2, {imm}')
    test(f'VINSERTPSmem_{imm}', FP32, f'vinsertps xmm4, xmm1, dword ptr [rsp+4], {imm}')
for imm in range(4):
    test(f'VEXTRACTPSr32_{imm}', FP32, f'mov rax, -1;vextractps eax, xmm1, {imm}')
    test(f'VEXTRACTPSmem_{imm}', FP32, f'vextractps dword ptr [rsp], xmm1, {imm}')
    test(f'VPINSRDr32_{imm}', INT, f'vpinsrd xmm4, xmm1, edi, {imm}')
    test(f'VPINSRDmem_{imm}', INT, f'vpinsrd xmm4, xmm1, dword ptr [rsp+8], {imm}')
for imm in range(2):
    test(f'VPINSRQr64_{imm}', INT, f'vpinsrq xmm4, xmm1, rsi, {imm}')
    test(f'VPINSRQmem_{imm}', INT, f'vpinsrq xmm4, xmm1, qword ptr [rsp+8], {imm}')
    test(f'VEXTRACTF128xmm_{imm}', INT, f'vextractf128 xmm4, ymm1, {imm}', ymm=True)
    test(f'VEXTRACTF128mem_{imm}', INT, f'vextractf128 xmmword ptr [rsp], ymm1, {imm}', ymm=True)
for imm in (0, 1, 4, 8, 15, 16, 20, 31, 32, 200):
    test(f'VPALIGNRxmm_{imm}', INT, f'vpalignr xmm4, xmm1, xmm2, {imm}')
test('VPALIGNRmem_7', INT, 'vpalignr xmm4, xmm1, xmmword ptr [rsp], 7')
for imm in ('0xff', '0x71', '0xf1', '0x3c', '0x00', '0x8f'):
    test(f'VDPPSxmm_{imm}', FP32, f'vdpps xmm4, xmm1, xmm2, {imm}')
test('VDPPSmem_ff', FP32, 'vdpps xmm4, xmm1, xmmword ptr [rsp], 0xff')
test('VDPPSymm_f3', FP32, 'vdpps ymm4, ymm1, ymm2, 0xf3', ymm=True)
test('VHSUBPSxmm', FP32, 'vhsubps xmm4, xmm1, xmm2')
test('VHSUBPSmem', FP32, 'vhsubps xmm4, xmm1, xmmword ptr [rsp]')
test('VSQRTPSxmm', FP32, 'vsqrtps xmm4, xmm1')
test('VSQRTPSmem', FP32, 'vsqrtps xmm4, xmmword ptr [rsp]')
test('VSQRTPSymm', FP32, 'vsqrtps ymm4, ymm1', ymm=True)
for imm in range(5):
    test(f'VROUNDPSxmm_{imm}', FP32, f'vroundps xmm4, xmm1, {imm | 8}')
    test(f'VROUNDPSymm_{imm}', FP32, f'vroundps ymm4, ymm1, {imm | 8}', ymm=True)
    test(f'VROUNDSSxmm_{imm}', FP32, f'vroundss xmm4, xmm1, xmm2, {imm | 8}')
    test(f'VROUNDSSmem_{imm}', FP32, f'vroundss xmm4, xmm1, dword ptr [rsp], {imm | 8}')
    test(f'VROUNDSDxmm_{imm}', FP64, f'vroundsd xmm4, xmm1, xmm2, {imm | 8}')
    test(f'VROUNDSDmem_{imm}', FP64, f'vroundsd xmm4, xmm1, qword ptr [rsp], {imm | 8}')
for op in ('vpmaxsd', 'vpminsd', 'vpmaxud', 'vpminud', 'vpsubsw'):
    test(f'{op.upper()}xmm', INT, f'{op} xmm4, xmm1, xmm2')
    test(f'{op.upper()}mem', INT, f'{op} xmm4, xmm1, xmmword ptr [rsp]')
test('VCVTPH2PSxmm', HALF, 'vcvtph2ps xmm4, xmm1')
test('VCVTPH2PSmem', HALF, 'vcvtph2ps xmm4, qword ptr [rsp+8]')
for op in ('blsi', 'blsr', 'blsmsk'):
    test(f'{op.upper()}r32', GPR, f'mov rax, -1;{op} eax, edi')
    test(f'{op.upper()}r64', GPR, f'{op} rax, rdi')
    test(f'{op.upper()}m32', GPR, f'mov rax, -1;{op} eax, dword ptr [rsp]')
    test(f'{op.upper()}m64', GPR, f'{op} rax, qword ptr [rsp+8]')
test('MOVBEm16', GPR, 'movbe word ptr [rsp], di;mov rax, qword ptr [rsp]')
test('MOVBEm32', GPR, 'movbe dword ptr [rsp], edi;mov rax, qword ptr [rsp]')
test('MOVBEm64', GPR, 'movbe qword ptr [rsp], rdi;mov rax, qword ptr [rsp]')

# --- upstream templates, VEX encodings ---
for op, inputs in (('vminps', FP32), ('vmaxps', FP32), ('vpshufb', INT), ('vpmaddwd', INT),
                   ('vpackssdw', INT), ('vpmaxsw', INT), ('vpminsw', INT), ('vpmaxub', INT),
                   ('vpmulhrsw', INT), ('vpmulld', INT), ('vpsignw', INT), ('vpsubb', INT),
                   ('vpsubw', INT), ('vpsubusb', INT), ('vpunpcklbw', INT), ('vpunpckhbw', INT),
                   ('vpunpcklwd', INT), ('vpunpckhwd', INT), ('vpunpckldq', INT),
                   ('vpunpckhdq', INT), ('vpunpckhqdq', INT), ('vpslld', INT), ('vpsllw', INT),
                   ('vpsrad', INT), ('vpsraw', INT), ('vpsrld', INT), ('vpsrlw', INT)):
    test(f'{op.upper()}xmm', inputs, f'{op} xmm4, xmm1, xmm2')
    test(f'{op.upper()}mem', inputs, f'{op} xmm4, xmm1, xmmword ptr [rsp]')
test('VPUNPCKLQDQmem', INT, 'vpunpcklqdq xmm4, xmm1, xmmword ptr [rsp]')
test('VMINPSymm', FP32, 'vminps ymm4, ymm1, ymm2', ymm=True)
test('VMAXPSymm', FP32, 'vmaxps ymm4, ymm1, ymm2', ymm=True)
for op in ('vpslld', 'vpsllw', 'vpsrad', 'vpsraw', 'vpsrld', 'vpsrlw'):
    for imm in (0, 3, 15, 31, 40):
        test(f'{op.upper()}imm_{imm}', INT, f'{op} xmm4, xmm1, {imm}')
for imm in range(4):
    test(f'VSHUFPDxmm_{imm}', FP64, f'vshufpd xmm4, xmm1, xmm2, {imm}')
    test(f'VSHUFPDmem_{imm}', FP64, f'vshufpd xmm4, xmm1, xmmword ptr [rsp], {imm}')
test('VMOVMSKPS', INT, 'mov rax, -1;vmovmskps eax, xmm1')
# Forms from __kernel_rem_pio2 (libc sin/cos of a big argument), upstream semantics.
test('VMOVSHDUPymm', FP32, 'vmovshdup ymm4, ymm1', ymm=True)
test('VMOVSHDUPxmm', FP32, 'vmovshdup xmm4, xmm1')
test('VMOVSLDUPymm', FP32, 'vmovsldup ymm4, ymm1', ymm=True)
test('VORPSymm', INT, 'vorps ymm4, ymm1, ymm2', ymm=True)
test('VPSHUFDmem_1b', INT, 'vpshufd xmm4, xmmword ptr [rsp], 0x1b')
test('VMOVHPDmem', FP64, 'vmovhpd xmm4, xmm1, qword ptr [rsp + 8]')
test('VROUNDSDalias_1', FP64, 'vroundsd xmm1, xmm2, xmm1, 9')
test('VCVTSI2SDm32', INT, 'vcvtsi2sd xmm4, xmm1, dword ptr [rsp]')
test('VCVTSI2SDr64', INT, 'vcvtsi2sd xmm4, xmm1, rdi')
test('VCVTTSD2SIr32', FP64, 'mov rax, -1;vcvttsd2si eax, xmm1')
test('VMOVDr32', INT, 'mov rax, -1;vmovd eax, xmm1')
test('ORREDUCE', INT, 'vinsertf128 ymm8, ymm1, xmm2, 1;vorps ymm0, ymm8, ymm3;vextractf128 xmm4, ymm0, 1;vorps ymm0, ymm0, ymm4;vshufps ymm4, ymm0, ymm0, 0xe;vorps ymm0, ymm0, ymm4;vmovshdup ymm4, ymm0;vorps ymm0, ymm0, ymm4;vmovd eax, xmm0;vzeroupper', ymm=True)
test('VLDDQU', INT, 'vlddqu xmm4, xmmword ptr [rsp]')

out.append('#endif  // HAS_FEATURE_AVX')
out.append('')

# --- atomic RMW (lock prefix, xchg with memory): memory at [rsp], read back into rax ---
regs = {8: ('sil', 'byte'), 16: ('si', 'word'), 32: ('esi', 'dword'), 64: ('rsi', 'qword')}
ATOM = """    push ARG1_64
    mov rax, -1"""


def atomic_test(name, body):
    global n
    n += 1
    out.append(f'TEST_BEGIN_64(PS4_{name}, 3)')
    out.append(f'TEST_INPUTS(\n    {GPR})')
    out.append(ATOM)
    out.extend('    ' + line for line in body.split(';'))
    out.append('    mov rax, qword ptr [rsp]')
    out.append('TEST_END_64')
    out.append('')


for bits, (reg, ptr) in regs.items():
    for op in ('add', 'sub', 'and', 'or', 'xor'):
        atomic_test(f'LOCK_{op.upper()}m{bits}r', f'lock {op} {ptr} ptr [rsp], {reg}')
        atomic_test(f'LOCK_{op.upper()}m{bits}i', f'lock {op} {ptr} ptr [rsp], 0x5a')
    atomic_test(f'LOCK_INCm{bits}', f'lock inc {ptr} ptr [rsp]')
    atomic_test(f'LOCK_DECm{bits}', f'lock dec {ptr} ptr [rsp]')
    atomic_test(f'LOCK_XADDm{bits}', f'lock xadd {ptr} ptr [rsp], {reg};mov rdx, rsi')
    atomic_test(f'XCHGm{bits}', f'xchg {ptr} ptr [rsp], {reg};mov rdx, rsi')
for bits in (16, 32, 64):
    reg, ptr = regs[bits]
    atomic_test(f'LOCK_ADDm{bits}imm8', f'lock add {ptr} ptr [rsp], -3')

# --- x87 environment: compare CW/SW only (FIP/FDP are real addresses natively) ---
X87ENV = """    sub rsp, 64
    fninit
    fnstenv [rsp]
    movzx eax, word ptr [rsp]
    movzx ebx, word ptr [rsp + 4]
    fnstcw word ptr [rsp + 40]
    movzx ecx, word ptr [rsp + 40]
    mov word ptr [rsp], 0x0c7f
    fldenv [rsp]
    fnstcw word ptr [rsp + 40]
    movzx edx, word ptr [rsp + 40]
    fninit
    mov qword ptr [rsp], 0
    mov qword ptr [rsp + 8], 0
    mov qword ptr [rsp + 16], 0
    mov qword ptr [rsp + 24], 0
    mov qword ptr [rsp + 32], 0
    mov qword ptr [rsp + 40], 0
    add rsp, 64"""
n += 1
out.append('TEST_BEGIN_64(PS4_FNSTENV_FLDENV, 1)')
out.append('TEST_INPUTS(0)')
out.append(X87ENV)
out.append('TEST_END_64')
out.append('')
print('\n'.join(out))
