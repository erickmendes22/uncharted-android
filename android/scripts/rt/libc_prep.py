#!/usr/bin/env python3
"""Differential test of libc.prx: export addresses by name and RELATIVE relocations.
Uses the module parsing from uncharted_pc/scripts (link_libc.module, prepare.nid).
Run in WSL: python3 -I libc_prep.py <game folder> <output>
Output (outside git: derived from the game): libc_funcs.h ({name, vaddr}), libc_relocs.bin (u64 off, u64 addend)."""
import struct
import sys
from pathlib import Path

PORT_SCRIPTS = Path(__file__).resolve().parents[3] / 'scripts'
sys.path.insert(0, str(PORT_SCRIPTS))
from link_libc import module  # noqa: E402
from prepare import nid  # noqa: E402

NAMES = ['strlen', 'strnlen', 'strcmp', 'strncmp', 'memcmp', 'memcpy', 'memmove', 'memset',
         'strchr', 'strrchr', 'strstr', 'strcpy', 'strncpy', 'strcat', 'abs', 'labs', 'llabs',
         'atoi', 'strtol', 'strtoul', 'qsort', 'bsearch', 'toupper', 'tolower', 'isdigit',
         'sqrt', 'sqrtf', 'floor', 'ceil', 'fabs', 'trunc', 'round', 'sin', 'cos', 'tan',
         'atan2', 'exp', 'log', 'log10', 'pow', 'fmod', 'sinf', 'cosf', 'atan2f', 'expf', 'logf',
         'powf', 'snprintf', 'sprintf', 'strtod', 'strtof', 'scalbn', 'ldexp', 'frexp',
         'modf', 'rint', 'nearbyint', 'lrint']


def main(game, out):
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    lib = module(Path(game) / 'sce_module' / 'libc.prx')
    exports = {}
    for s in lib['symbols']:
        if s['section'] and s['value'] and s['identity']:
            exports.setdefault(s['identity'][0], s)
    lines, found = [], 0
    for name in NAMES:
        s = exports.get(nid(name))
        if s:
            found += 1
            lines.append(f'    {{"{name}", 0x{s["value"]:x}, {s["type"]}}},')
    (out / 'libc_funcs.h').write_text(
        '/* Generated by libc_prep.py — libc.prx exports (image vaddr). */\n'
        'static const struct { const char *name; unsigned long long vaddr; int type; } libc_funcs[] = {\n'
        + '\n'.join(lines) + '\n};\n')
    rel = [(t, a) for t, kind, sym, a in lib['relocs'] if kind == 8]  # R_X86_64_RELATIVE
    other = sum(1 for t, kind, sym, a in lib['relocs'] if kind != 8)
    (out / 'libc_relocs.bin').write_bytes(b''.join(struct.pack('<QQ', t, a) for t, a in rel))
    # Symbol relocations (imports and references to its own exports): offset type nid defined addend.
    # 1 = R_X86_64_64, 6 = GLOB_DAT, 7 = JUMP_SLOT; TLS (16-18) separately, not handled yet.
    with open(out / 'libc_imports.txt', 'w') as f:
        for t, kind, sym, a in lib['relocs']:
            if kind in (1, 6, 7):
                s = lib['symbols'][sym]
                nid_ = s['identity'][0] if s['identity'] else '?'
                defined = s['value'] if s['section'] else 0
                f.write(f'{t:x} {kind} {nid_} {defined:x} {a}\n')
    known = {'__error', '__stack_chk_fail', '__stack_chk_guard', 'pthread_mutex_lock',
             'pthread_mutex_unlock', 'scePthreadMutexLock', 'scePthreadMutexUnlock',
             'sceKernelGetTscFrequency', 'sceKernelReadTsc', 'malloc', 'free'}
    (out / 'libc_known_nids.h').write_text(
        '/* Generated by libc_prep.py — NID of imports the harness implements. */\n' +
        ''.join(f'#define NID_{n.lstrip("_")} "{nid(n)}"\n' for n in sorted(known)))
    print(f'libc.prx: {len(exports)} exports, found {found}/{len(NAMES)} test functions; '
          f'{len(rel)} RELATIVE relocs, {other} symbolic (left unresolved)')


if __name__ == '__main__':
    main(*sys.argv[1:3])
