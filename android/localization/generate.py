#!/usr/bin/env python3
"""Generate native translations from the same catalog packaged for Android Java UI.
English technical diagnostics intentionally remain a fallback, as in the ISS port.
"""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[2]
rows=json.loads((root/'android/localization/strings.json').read_text())
langs=['en','pt','es','fr','de','it','ru','ja','ko','zh','tr','pl']
def q(s):return json.dumps(s,ensure_ascii=False)
s='''// Generated by android/localization/generate.py. Do not edit independently.
// SPDX-License-Identifier: GPL-2.0-or-later
#pragma once
#include <cstdlib>
#include <cstring>
namespace BbLocale {
inline const char* Text(const char* english) {
    static const int language=[] {
        const char* selected=std::getenv("BB_UI_LANGUAGE");
        const char* codes[]={"en","pt","es","fr","de","it","ru","ja","ko","zh","tr","pl"};
        if(selected)for(int i=0;i<12;++i)if(std::strcmp(selected,codes[i])==0)return i;
        return 0;
    }();
    if(language==0)return english;
    static const char* const rows[][12]={
'''
for k,v in sorted(rows.items()):s+='        {'+','.join(q(k if c=='en' else v.get(c,k)) for c in langs)+'},\n'
s+='''    };
    for(const auto& row:rows)if(std::strcmp(english,row[0])==0)return row[language];
    return english;
}
} // namespace BbLocale
'''
(root/'gpu/shim/bbport_locale.h').write_text(s)
print(len(rows),'catalog entries validated')
